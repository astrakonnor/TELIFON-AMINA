const SENDERS = ['Максим', 'Миша', 'Вичат', 'Мансур', 'a.', 'Нест', 'Шиппис', 'ложка', 'Вета', 'sorrow', 'Рин', 'Рай', 'Neariver', 'lina', 'Мел', 'múrx', 'Лариса', 'pink pony club', 'vataarey', 'Амина', 'Victoria', 'Александра Луговкина', 'Неизвестный'];

function normalize(value) { return String(value || '').normalize('NFKC').trim().toLocaleLowerCase('ru'); }

function isTarget(ctx, groupName = '') {
    const active = ctx?.characters?.[ctx.characterId];
    const names = [ctx?.name2, active?.name, active?.data?.name];
    return names.some(name => normalize(name).includes('sistavern') && normalize(name).includes('дело'))
        || normalize(groupName) === 'sistavern.chat';
}

function playerIsAmina(ctx) {
    const n = normalize(ctx?.name1);
    return n.includes('амин') || n.includes('эщкере') || n.includes('amina');
}

export function sistavernVoicePrompt(ctx, { contactName = '', members = [], groupName = '', all = false } = {}) {
    if (!isTarget(ctx, groupName)) return '';
    const amina = playerIsAmina(ctx);
    const wanted = [contactName, ...members].map(normalize).filter(Boolean);
    let selected = all ? VOICES : VOICES.filter(voice => voice.aliases.some(alias => wanted.includes(normalize(alias))));
    if (amina) selected = selected.filter(voice => voice.name !== 'Амина');
    if (!selected.length) return '';
    const head = [
        'SISTAVERN — манера переписки (реальные привычки чата, 81 тыс. сообщений). Пиши на русском короткими отдельными сообщениями: у большинства 15–40 знаков, серия из 1–3 реплик вместо абзаца, мало запятых, редкая точка в конце, живые опечатки только изредка. У каждого свой отпечаток: Максим, Миша, Рай, Лариса — всегда с заглавной; Мансур, a., Шиппис, ложка, Вета, Рин, lina — почти всегда со строчной; остальные смешанно.',
        'МАКСИМ-БАРОМЕТР: «чёрт/гадем» стоят почти в каждой его реплике (а не раз в абзац) — это норма, не убирай. Когда его реально задело, он пишет коротко и БЕЗ них; окружающие замечают это. Другие подражают ему редко.',
        'ШУМ: в групповом чате всегда идёт параллельная болтовня (роут, гемка, пресеты, еда); кто-то отвечает невпопад. Допустимые отправители (from): ' + SENDERS.filter(n => !(amina && n === 'Амина')).join(', ') + '. Не придумывай новых людей, не пиши за игрока' + (amina ? ' (игрок играет за Амину)' : '') + '. Не раскрывай решение без улик. Примеры — образцы стиля, а не события.'
    ].join('\n');
    return head + '\n' + selected.map(voice => voice.name + ': ' + voice.short + '. Образцы: ' + voice.examples.map(q => '«' + q + '»').join(' / ')).join('\n');
}

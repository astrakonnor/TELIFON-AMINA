function normalize(value) { return String(value || '').normalize('NFKC').trim().toLocaleLowerCase('ru'); }
function isTarget(ctx, groupName = '') {
    const active = ctx?.characters?.[ctx.characterId];
    const names = [ctx?.name2, active?.name, active?.data?.name];
    return names.some(name => normalize(name).includes('sistavern') && normalize(name).includes('дело'))
        || normalize(groupName) === 'sistavern.chat';
}
export function sistavernVoicePrompt(ctx, { contactName = '', members = [], groupName = '', all = false } = {}) {
    if (!isTarget(ctx, groupName)) return '';
    const selected = all ? VOICES : VOICES.filter(voice => [contactName, ...members].some(name =>
        voice.aliases.some(alias => normalize(alias) === normalize(name))));
    if (!selected.length) return '';
    return 'SISTAVERN — индивидуальная манера переписки. Пиши на русском живыми отдельными сообщениями: разговорные сокращения, обычно мало пунктуации, случайные естественные опечатки; не делай каждую фразу одинаковой или нарочно неграмотной. Сохраняй голос и знания конкретного отправителя, не пиши за игрока. Цитаты ниже — примеры стиля из чата, а не события сюжета; не повторяй их дословно без причины. Если игрок — Амина, не генерируй сообщения от неё. Контекст лорбука и текущая ситуация важнее шаблонных фраз.\n' +
        selected.map(voice => voice.name + ': ' + voice.style + '. Примеры: ' + voice.examples.map(q => '«' + q + '»').join(' / ')).join('\n');
}
